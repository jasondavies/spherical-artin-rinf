#!/usr/bin/env python3
"""Generate ArtinRinf/Types/{H4,E6,E7,E8}.lean from a template (H3/F4 are hand-written).
The generated files contain no data; they only invoke the generic lemmas with `decide +kernel`."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
INFO = {  # name: (Mathlib matrix, rank, |T|, outer kind, description of hOut)
    'H4': ('H₄', 4, 60, 'stable'),
    'E6': ('E₆', 6, 36, None),
    'E7': ('E₇', 7, 63, None),
    'E8': ('E₈', 8, 120, None),
    'D5': ('D₅', 5, 20, None),
}
# Lean expression for the Coxeter matrix, and extra imports (Mathlib's `CoxeterMatrix.D 5` is not D₅)
MATEXPR = {'D5': ('ArtinRinf.D₅', 'import ArtinRinf.CoxD5\n', '(defined in `CoxD5.lean`)')}


def split_block(name, N, k, d):
    """For large types: split the big `decide` checks into many small theorems (bounded kernel
    memory, parallel checking)."""
    out = []
    for r in range(N):
        out.append(f'theorem ok_none_{r} : ∀ s, par {r} s = none → rep (lab {r} s) = ({r}, s) := by decide +kernel')
        out.append(f'theorem ok_some_{r} : ∀ s i, par {r} s = some i →\n    lab (gens i {r}) (gens i s) = lab {r} s ∧ depth (gens i {r}) (gens i s) < depth {r} s := by\n  decide +kernel')
    out.append('theorem ok_none : ∀ r s, par r s = none → rep (lab r s) = (r, s) := by\n  intro r\n  fin_cases r\n' +
               '\n'.join(f'  · exact ok_none_{r}' for r in range(N)))
    out.append('theorem ok_some : ∀ r s i, par r s = some i →\n    lab (gens i r) (gens i s) = lab r s ∧ depth (gens i r) (gens i s) < depth r s := by\n  intro r\n  fin_cases r\n' +
               '\n'.join(f'  · exact ok_some_{r}' for r in range(N)))
    for w in range(k):
        for j in range(d):
            out.append(f'theorem orb_{w}_{j} : orbMat lab {w} *ᵥ U0 {j} = mu0 {w} • U0 {j} := by decide +kernel')
    out.append('theorem orbital_scalar : ∀ ω j, orbMat lab ω *ᵥ U0 j = mu0 ω • U0 j := by\n  intro ω j\n  fin_cases ω <;> fin_cases j\n' +
               '\n'.join(f'  · exact orb_{w}_{j}' for w in range(k) for j in range(d)))
    return '\n\n'.join(out) + '\n'


def gen(name):
    mat, n, N, outer = INFO[name]
    mexpr, extra_import, mdesc = MATEXPR.get(name, (f'CoxeterMatrix.{mat}', '', "(Mathlib's)"))
    data = open(os.path.join(HERE, '..', 'ArtinRinf', 'Data', f'{name}.lean')).read()
    k = int(re.search(r'def lab : Fin \d+ → Fin \d+ → Fin (\d+)', data).group(1))
    d = int(re.search(r'def U0 : Fin (\d+)', data).group(1))
    s = f'''/-
# Type {mat}: the finite certificates, checked by `decide +kernel`, and the final theorem

Generated by scripts/gen_types.py.
-/
import ArtinRinf.Certificate
{extra_import}import ArtinRinf.Data.{name}

set_option maxHeartbeats 0

namespace ArtinRinf.{name}

open {name}Data ArtinGroup Matrix

noncomputable section

/-- The Coxeter matrix `{mat}` {mdesc}. -/
abbrev M : CoxeterMatrix (Fin {n}) := {mexpr}

theorem gensFun_invol : ∀ i x, gensFun i (gensFun i x) = x := by decide +kernel

/-- The permutation of the {N} reflections induced by `s_i`. -/
def gens (i : Fin {n}) : Equiv.Perm (Fin {N}) :=
  ⟨gensFun i, gensFun i, gensFun_invol i, gensFun_invol i⟩

theorem gens_sq : ∀ i, gens i * gens i = 1 := by decide +kernel
theorem gens_fix : ∀ i, gens i (sidx i) = sidx i := by decide +kernel
/-- Lemma 2.3 for `{mat}`: the braid relations hold in `ℤ^T ⋊ Perm T`. -/
theorem braid_ok : ∀ i j, i ≠ j → braidWord (affGen ℤ gens sidx i) (affGen ℤ gens sidx j) (M i j) =
    braidWord (affGen ℤ gens sidx j) (affGen ℤ gens sidx i) (M i j) := by decide +kernel
theorem cox2_ok : ∀ i j,
    (affGen (ZMod 2) gens sidx i * affGen (ZMod 2) gens sidx j) ^ (M i j) = 1 := by
  decide +kernel
theorem orb_ok : ∀ t, ((orbWord t).1.map gens).prod (sidx (orbWord t).2) = t := by
  decide +kernel

/-- The reflection data of `{mat}`. -/
def D : ReflData M (Fin {N}) where
  gens := gens
  sidx := sidx
  gens_sq := gens_sq
  gens_fix := gens_fix
  braid := braid_ok
  cox2 := cox2_ok
  orbWord := orbWord
  orb := orb_ok

{{SPLIT_CERT}}
/-- The orbital certificate. -/
def C : OrbitalCert gens {k} where
  lab := lab
  rep := rep
  par := par
  depth := depth
  ok_none := ok_none
  ok_some := ok_some

{{SPLIT_ORB}}
/-- **Good constituent** (dimension {d}): every matrix commuting with `ρ(W)` acts on it by a
scalar. -/
theorem commScalar_U0 : CommScalar D.ρ (spanZ U0) :=
  commScalar_of_cert D.ρ gens D.hgen C U0 mu0 orbital_scalar

/-- Witnesses for the trivial outer class (`π = 1`). -/
theorem witness_inner : Witness D.ρ 1 :=
  Or.inl ⟨_, commScalar_U0, D.stableWitness 1 U0 [] [innerMinusGen] innerPlusC innerMinusC
    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)⟩
'''
    if N >= 100:
        blk = split_block(name, N, k, d)
        i = blk.index('theorem orb_0_0')
        s = s.replace('{SPLIT_CERT}', blk[:i]).replace('{SPLIT_ORB}', blk[i:])
    else:
        s = s.replace('{SPLIT_CERT}', '''theorem ok_none : ∀ r s, par r s = none → rep (lab r s) = (r, s) := by decide +kernel
theorem ok_some : ∀ r s i, par r s = some i →
    lab (gens i r) (gens i s) = lab r s ∧ depth (gens i r) (gens i s) < depth r s := by
  decide +kernel
''').replace('{SPLIT_ORB}', '''theorem orbital_scalar : ∀ ω j, orbMat lab ω *ᵥ U0 j = mu0 ω • U0 j := by decide +kernel
''')
    if outer == 'stable':
        s += f'''
theorem pi0Fun_invol : ∀ x, pi0Fun (pi0Fun x) = x := by decide +kernel

/-- The outer permutation `π₀` (Galois conjugation `√5 ↦ -√5` followed by a coordinate
permutation; paper, Appendix B). -/
def pi0 : Equiv.Perm (Fin {N}) := ⟨pi0Fun, pi0Fun, pi0Fun_invol, pi0Fun_invol⟩

/-- Sanity check: `π₀` normalises `ρ(W)` (explicit words). -/
theorem pi0_normalises : ∀ i, pi0 * gens i * pi0⁻¹ = ((pi0ConjWord i).map gens).prod := by
  decide +kernel

/-- Witnesses for the nontrivial outer class (`π = π₀`; stable case). -/
theorem witness_outer : Witness D.ρ pi0 :=
  Or.inl ⟨_, commScalar_U0, D.stableWitness pi0 U0 outerPlusWord outerMinusWord outerPlusC
    outerMinusC (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)⟩

/-- **Main theorem for `{mat}`.**  Assuming
* `hW`: `W({mat})` is finite (classical);
* `hCP`: the pure Artin group is characteristic (Cohen–Paris, Thm 1.4; computer-assisted);
* `hBr`: `H₁(P;ℤ) ≅ ℤ^{N}` (Brieskorn; Orlik–Terao; {N} = number of reflections);
* `hOut`: every automorphism of `ρ(W) ≅ W/Z(W)` is conjugation by an element of `ρ(W)` or of
  `ρ(W)π₀` (computed: `|Out(W/Z)| = 2`, paper Appendix B),
every automorphism of `A({mat})` has infinite Reidemeister number. -/
theorem artin_{name}_R_infty (hW : Finite M.Group) (hCP : (pure M).Characteristic)
    (hBr : Nonempty (Abelianization (pure M) ≃* Multiplicative (Fin {N} → ℤ)))
    (hOut : OutGeneratedBy D.ρ.range pi0) :
    ∀ φ : ArtinGroup M ≃* ArtinGroup M, reidemeisterAut φ = ⊤ :=
  D.rinf hW hCP hBr pi0 hOut witness_inner witness_outer

end

end ArtinRinf.{name}
'''
    else:
        ref = {'E6': 'computed, paper Appendix B', 'E7': 'computed, paper Appendix B',
               'E8': 'proved by hand in paper Proposition B.2',
               'D5': 'computed, `code/indep/out_check.py`; also Franzsen–Howlett Thm 31(3)'}[name]
        s += f'''
/-- **Main theorem for `{mat}`.**  Assuming
* `hW`: `W({mat})` is finite (classical);
* `hCP`: the pure Artin group is characteristic (Cohen–Paris, Thm 1.4; computer-assisted);
* `hBr`: `H₁(P;ℤ) ≅ ℤ^{N}` (Brieskorn; Orlik–Terao; {N} = number of reflections);
* `hOut`: every automorphism of `ρ(W) ≅ W/Z(W)` is inner ({ref}),
every automorphism of `A({mat})` has infinite Reidemeister number. -/
theorem artin_{name}_R_infty (hW : Finite M.Group) (hCP : (pure M).Characteristic)
    (hBr : Nonempty (Abelianization (pure M) ≃* Multiplicative (Fin {N} → ℤ)))
    (hOut : OutGeneratedBy D.ρ.range 1) :
    ∀ φ : ArtinGroup M ≃* ArtinGroup M, reidemeisterAut φ = ⊤ :=
  D.rinf hW hCP hBr 1 hOut witness_inner witness_inner

end

end ArtinRinf.{name}
'''
    open(os.path.join(HERE, '..', 'ArtinRinf', 'Types', f'{name}.lean'), 'w').write(s)


if __name__ == '__main__':
    for nm in sys.argv[1:]:
        gen(nm)
