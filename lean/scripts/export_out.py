#!/usr/bin/env python3
"""Export an enumeration of rho(W) for the Lean verification of Out(rho(W)) (H3 only).
Writes ArtinRinf/Data/<X>Out.lean. Untrusted: everything is re-checked in Lean by `decide +kernel`."""
import sys, os
sys.dont_write_bytecode = True  # do not create __pycache__ inside ../code
from collections import deque
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'code', 'indep'))
from rootsys import RootSystem

def compose(p, q): return tuple(p[q[x]] for x in range(len(q)))

def main(name):
    rs = RootSystem(name); N = rs.N; n = rs.n
    gens = [tuple(g) for g in rs.gens]
    e = tuple(range(N))
    elts = [e]; words = {e: []}; dq = deque([e])
    while dq:
        x = dq.popleft()
        for i, g in enumerate(gens):
            y = compose(g, x)                 # left multiplication by s_i
            if y not in words:
                words[y] = [i] + words[x]; elts.append(y); dq.append(y)
    K = len(elts); idx = {x: k for k, x in enumerate(elts)}
    inv = lambda p: tuple(sorted(range(N), key=lambda r: p[r]))
    mul = [[idx[compose(g, x)] for x in elts] for g in gens]
    invIdx = [k for k, x in enumerate(elts) if compose(x, x) == e and x != e]
    # conjugator table for Coxeter-like triples (H3 only: 3 generators)
    table = []
    if n == 3:
        import indep_check
        pi0, _ = indep_check.explicit_pi0(name, rs); pi0 = tuple(int(x) for x in pi0)
        def order_ok(a, b, m):
            x = e; p = compose(a, b)
            for _ in range(m): x = compose(x, p)
            return x == e
        Mx = rs.coxeter
        pinv = lambda p: tuple(sorted(range(N), key=lambda r: p[r]))
        cands = [(k, False, elts[k]) for k in range(K)] + [(k, True, compose(elts[k], pi0)) for k in range(K)]
        for k0 in invIdx:
            for k1 in invIdx:
                for k2 in invIdx:
                    y = [elts[k0], elts[k1], elts[k2]]
                    if len({k0, k1, k2}) < 3: continue
                    if not all(order_ok(y[i], y[j], Mx[i][j]) for i in range(3) for j in range(3)): continue
                    for (k, b, c) in cands:
                        ci = pinv(c)
                        if all(compose(compose(c, gens[i]), ci) == y[i] for i in range(3)):
                            table.append((k0, k1, k2, k, b)); break
                    else:
                        raise RuntimeError('no conjugator')
    print(name, 'order', K, 'involutions', len(invIdx), file=sys.stderr)
    fl = lambda xs: '![' + ', '.join(map(str, xs)) + ']'
    L = lambda xs: '[' + ', '.join(map(str, xs)) + ']'
    out = [f'/-\nGenerated by scripts/export_out.py -- do not edit. Enumeration of rho(W({name})), |rho(W)| = {K}.\n-/',
           'import Mathlib\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n',
           f'namespace ArtinRinf.{name}Out\n\nnoncomputable section\n',
           f'def eltFun : Fin {K} → Fin {N} → Fin {N} := ![\n  ' + ',\n  '.join(fl(x) for x in elts) + ']\n',
           f'def eltInvFun : Fin {K} → Fin {N} → Fin {N} := ![\n  ' + ',\n  '.join(fl(inv(x)) for x in elts) + ']\n',
           f'def word : Fin {K} → List (Fin {n}) := ![\n  ' + ',\n  '.join(L(words[x]) for x in elts) + ']\n',
           f'def mulTab : Fin {n} → Fin {K} → Fin {K} := ![\n  ' + ',\n  '.join(fl(r) for r in mul) + ']\n',
           f'def invIdx : List (Fin {K}) := {L(invIdx)}\n',
           f'/-- (k0, k1, k2, k, b): conjugator for each Coxeter-like triple -/',
           f'def conjTable : List (Fin {K} × Fin {K} × Fin {K} × Fin {K} × Bool) := [' +
           ', '.join(f'({a}, {b}, {c}, {d}, {"true" if e_ else "false"})' for a, b, c, d, e_ in table) + ']\n',
           'end\n', f'end ArtinRinf.{name}Out\n']
    open(os.path.join(HERE, '..', 'ArtinRinf', 'Data', f'{name}Out.lean'), 'w').write('\n'.join(out))



def bt(xs, keys=None, lo=0, hi=None):
    """balanced BT literal; keys (sorted) are the lookup indices of the entries (default 0..n-1)"""
    if keys is None: keys = list(range(len(xs)))
    if hi is None: hi = len(xs)
    if hi - lo == 1: return f'(.leaf ({xs[lo]}))'
    mid = (lo + hi) // 2
    return f'(.node {keys[mid]} {bt(xs, keys, lo, mid)} {bt(xs, keys, mid, hi)})'


def main_f4():
    """F4: enumeration of rho(W) (576 elements), involutions, relation tables, conjugators."""
    import indep_check
    name = 'F4'
    rs = RootSystem(name); N = rs.N; n = rs.n
    gens = [tuple(g) for g in rs.gens]
    e = tuple(range(N))
    elts = [e]; words = {e: []}; dq = deque([e])
    while dq:
        x = dq.popleft()
        for i, g in enumerate(gens):
            y = compose(g, x)
            if y not in words:
                words[y] = [i] + words[x]; elts.append(y); dq.append(y)
    K = len(elts); idx = {x: k for k, x in enumerate(elts)}
    inv = lambda p: tuple(sorted(range(N), key=lambda r: p[r]))
    mul = [[idx[compose(g, x)] for x in elts] for g in gens]
    invL = [k for k, x in enumerate(elts) if compose(x, x) == e and x != e]
    I = len(invL)
    def order(p):
        x = p; k = 1
        while x != e: x = compose(x, p); k += 1
        return k
    ordtab = [[order(compose(elts[a], elts[b])) for b in invL] for a in invL]
    rel = {m: [[ordtab[a][b] == m for b in range(I)] for a in range(I)] for m in (2, 3, 4)}
    Mx = rs.coxeter
    assert [Mx[0][1], Mx[1][2], Mx[2][3], Mx[0][2], Mx[0][3], Mx[1][3]] == [3, 4, 3, 2, 2, 2]
    pi0, _ = indep_check.explicit_pi0(name, rs); pi0 = tuple(int(x) for x in pi0)
    cands = [(k, False, elts[k]) for k in range(K)] + [(k, True, compose(elts[k], pi0)) for k in range(K)]
    conj_of_tuple = {}
    for k, b, c in cands:
        ci = inv(c)
        y = tuple(idx[compose(compose(c, g), ci)] for g in gens)
        conj_of_tuple.setdefault(y, (k, b))
    table = {}
    for a in range(I):
        for b_ in range(I):
            if not rel[3][a][b_]: continue
            for c in range(I):
                if not (rel[2][a][c] and rel[4][b_][c]): continue
                for d in range(I):
                    if not (rel[2][a][d] and rel[2][b_][d] and rel[3][c][d]): continue
                    y = (invL[a], invL[b_], invL[c], invL[d])
                    table[((a * I + b_) * I + c) * I + d] = conj_of_tuple[y]
    print(name, 'order', K, 'involutions', I, 'tuples', len(table), file=sys.stderr)
    keys = sorted(table)
    fin = lambda rows: [list(map(str, r)) for r in rows]
    B = lambda v: 'true' if v else 'false'
    out = [f'/-\nGenerated by scripts/export_out.py -- do not edit. Enumeration of rho(W({name})), |rho(W)| = {K},\n'
           f'{I} involutions, {len(table)} Coxeter-like tuples.\n-/',
           'import ArtinRinf.BT\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n',
           f'namespace ArtinRinf.{name}Out\n\nopen ArtinRinf\n\nnoncomputable section\n',
           f'def eltFun : Fin {K} → Fin {N} → Fin {N} := fun i j =>\n  BT.get (BT.get ({bt([bt(r) for r in fin(elts)])} : BT (BT (Fin {N}))) i.val) j.val\n',
           f'def eltInvFun : Fin {K} → Fin {N} → Fin {N} := fun i j =>\n  BT.get (BT.get ({bt([bt(r) for r in fin([inv(x) for x in elts])])} : BT (BT (Fin {N}))) i.val) j.val\n',
           f'def word : Fin {K} → List (Fin {n}) := fun i =>\n  BT.get ({bt(["[" + ", ".join(map(str, words[x])) + "]" for x in elts])} : BT (List (Fin {n}))) i.val\n',
           f'def mulTab : Fin {n} → Fin {K} → Fin {K} := fun i j =>\n  BT.get (BT.get ({bt([bt(r) for r in fin(mul)])} : BT (BT (Fin {K}))) i.val) j.val\n',
           f'def invL : Fin {I} → Fin {K} := fun i => BT.get ({bt(list(map(str, invL)))} : BT (Fin {K})) i.val\n']
    for m in (2, 3, 4):
        out.append(f'def rel{m} : Fin {I} → Fin {I} → Bool := fun i j =>\n  BT.get (BT.get ({bt([bt([B(v) for v in r]) for r in rel[m]])} : BT (BT Bool)) i.val) j.val\n')
    out.append(f'/-- conjugator `(k, b)` for each Coxeter-like tuple, keyed by `((a*{I}+b)*{I}+c)*{I}+d` -/')
    out.append(f'def conjOf (a b c d : Fin {I}) : Fin {K} × Bool :=\n  BT.get ({bt([f"{table[k][0]}, {B(table[k][1])}" for k in keys], keys)} : BT (Fin {K} × Bool))\n'
               f'    (((a.val * {I} + b.val) * {I} + c.val) * {I} + d.val)\n')
    out += ['end\n', f'end ArtinRinf.{name}Out\n']
    open(os.path.join(HERE, '..', 'ArtinRinf', 'Data', f'{name}Out.lean'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    for nm in sys.argv[1:]:
        if nm == 'F4': main_f4()
        else: main(nm)
