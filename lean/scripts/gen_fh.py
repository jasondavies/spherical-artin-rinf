#!/usr/bin/env python3
"""Generate ArtinRinf/Types/<X>FH.lean: the Franzsen–Howlett versions of the main theorems
(no `hOut`), from the data in ArtinRinf/Data/<X>Tree.lean.  No data in the generated files."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
INFO = {'H3': ('H₃', 3, 15, True), 'F4': ('F₄', 4, 24, True), 'H4': ('H₄', 4, 60, True),
        'E6': ('E₆', 6, 36, False), 'E7': ('E₇', 7, 63, False), 'E8': ('E₈', 8, 120, False)}


def gen(name):
    mat, n, N, outer = INFO[name]
    pi0 = 'pi0' if outer else '1'
    pi0_ok = ('theorem pi0_ok : ∀ t, pi0 * rp t * pi0⁻¹ = rp (pi0 t) := by decide +kernel' if outer else
              'theorem pi0_ok : ∀ t, (1 : Equiv.Perm (Fin %d)) * rp t * 1⁻¹ = rp ((1 : Equiv.Perm (Fin %d)) t) := by\n  intro t; simp' % (N, N))
    wout = 'witness_outer' if outer else 'witness_inner'
    s = f'''/-
# Type {mat}: the Franzsen–Howlett route (paper v3, Lemma 4.1) — no `hOut`

Generated by scripts/gen_fh.py.  Every reflection-preserving automorphism of `ρ(W)` is conjugation by an
element of `ρ(W)` {"or `ρ(W)π₀`" if outer else ""}: kernel-checked search-tree certificate
(`Data/{name}Tree.lean`, produced by `scripts/export_tree.py`).
-/
import ArtinRinf.FH
import ArtinRinf.Types.{name}
import ArtinRinf.Data.{name}Tree

set_option maxHeartbeats 0

namespace ArtinRinf.{name}

open {name}Tree ArtinGroup

noncomputable section

theorem rp_invol : ∀ t x, rpFun t (rpFun t x) = x := by decide +kernel

/-- The reflection permutations `ρ(t)`, `t ∈ T`. -/
def rp (t : Fin {N}) : Equiv.Perm (Fin {N}) := ⟨rpFun t, rpFun t, rp_invol t, rp_invol t⟩

theorem rp_sidx : ∀ i, rp (D.sidx i) = D.gens i := by decide +kernel
theorem rp_equiv : ∀ i t, D.gens i * rp t * D.gens i = rp (D.gens i t) := by decide +kernel
theorem rp_inj : ∀ a b, rp a = rp b → a = b := by decide +kernel

/-- Reflection permutations of `{mat}`. -/
def R : D.RpData := ⟨rp, rp_sidx, rp_equiv, rp_inj⟩

{pi0_ok}

theorem tree_ext_ok : ∀ q c, (node q).length < {n} → ReflData.validExt R.rp M (node q) c = true →
    node (child q c) = node q ++ [repF q c] ∧
      (node q).all (fun p => decide (D.wordPerm (hw q c) p = p)) = true ∧
      D.wordPerm (hw q c) (repF q c) = c := by
  decide +kernel

theorem tree_leaf_ok : ∀ q, (node q).length = {n} → ∀ i : Fin {n},
    (node q)[i.val]? = some ((D.wordPerm (leafW q) * (if leafE q then {pi0} else 1)) (D.sidx i)) := by
  decide +kernel

/-- The search-tree certificate for `{mat}`. -/
def TC : D.TreeCert R {pi0} where
  K := K
  node := node
  root := root
  root_ok := by decide +kernel
  child := child
  repF := repF
  hw := hw
  ext_ok := tree_ext_ok
  leafW := leafW
  leafE := leafE
  leaf_ok := tree_leaf_ok
  pi0_ok := pi0_ok

theorem gens_isOrd : ∀ i j : Fin {n}, i.val < j.val → isOrdB (D.gens i * D.gens j) (M i j) = true := by
  decide +kernel

/-- **Main theorem for `{mat}`, Franzsen–Howlett version.**  Hypotheses: only the cited theorems
`hW` (`W` finite), `hCP` (Cohen–Paris), `hBr` (Brieskorn, `H₁(P) ≅ ℤ^{N}`) and `hFH`
(Franzsen–Howlett, [FH03, Thm. 31]: `Aut(W) = R(W)·A(W)`). -/
theorem artin_{name}_R_infty_FH (hW : Finite M.Group) (hCP : (pure M).Characteristic)
    (hBr : Nonempty (Abelianization (pure M) ≃* Multiplicative (Fin {N} → ℤ)))
    (hFH : FranzsenHowlett M) :
    ∀ φ : ArtinGroup M ≃* ArtinGroup M, reidemeisterAut φ = ⊤ :=
  D.rinf_FH R {pi0} TC gens_isOrd hW hCP hBr hFH witness_inner {wout}

end

end ArtinRinf.{name}
'''
    open(os.path.join(HERE, '..', 'ArtinRinf', 'Types', f'{name}FH.lean'), 'w').write(s)


if __name__ == '__main__':
    for nm in sys.argv[1:]:
        gen(nm)
