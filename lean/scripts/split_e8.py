#!/usr/bin/env python3
"""Split the generated ArtinRinf/Types/E8.lean into several modules so that `lake build` checks
the many small `decide +kernel` certificates in parallel.  Run after gen_types.py E8.
Output: ArtinRinf/Types/E8/{Gens,Rows0..3,Orb0..2}.lean and a slimmed ArtinRinf/Types/E8.lean."""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
T = os.path.join(HERE, '..', 'ArtinRinf', 'Types')
src = open(os.path.join(T, 'E8.lean')).read()

hdr_end = src.index('/-- The Coxeter matrix')
header = src[:hdr_end]              # comment, imports, options, namespace, open, noncomputable section
pre = header[:header.index('import')]
body_opts = header[header.index('set_option'):]
d_end = src.index('  orb := orb_ok\n') + len('  orb := orb_ok\n')
gens_part = src[hdr_end:d_end]
rest = src[d_end:]

# split the theorems in `rest`
chunks = re.split(r'\n(?=theorem |/-- |def )', rest)
rows, orbs, tail = [], [], []
for c in chunks:
    if re.match(r'theorem ok_(none|some)_\d+ ', c): rows.append(c)
    elif re.match(r'theorem orb_\d+_\d+ ', c): orbs.append(c)
    else: tail.append(c)

os.makedirs(os.path.join(T, 'E8'), exist_ok=True)
def write(name, imports, parts, doc):
    s = (f'/-\n# E8 certificates: {doc}\n\nGenerated by scripts/split_e8.py.\n-/\n' +
         ''.join(f'import {i}\n' for i in imports) + '\n' + body_opts + '\n'.join(parts) + '\n\nend\n\nend ArtinRinf.E8\n')
    open(os.path.join(T, 'E8', f'{name}.lean'), 'w').write(s)

write('Gens', ['ArtinRinf.Certificate', 'ArtinRinf.Data.E8'], [gens_part], 'generators, Lemma 2.4 data')
nrow = 4
per = (len(rows) + nrow - 1) // nrow
for r in range(nrow):
    write(f'Rows{r}', ['ArtinRinf.Types.E8.Gens'], rows[r * per:(r + 1) * per], f'orbital certificate, part {r}')
ks = sorted(set(int(re.match(r'theorem orb_(\d+)_', c).group(1)) for c in orbs))
for w in ks:
    write(f'Orb{w}', ['ArtinRinf.Certificate', 'ArtinRinf.Data.E8'],
          [c for c in orbs if c.startswith(f'theorem orb_{w}_')], f'orbital matrix {w} is scalar on U0')
imports = ['ArtinRinf.Types.E8.Gens'] + [f'ArtinRinf.Types.E8.Rows{r}' for r in range(nrow)] + \
          [f'ArtinRinf.Types.E8.Orb{w}' for w in ks]
main = (pre + ''.join(f'import {i}\n' for i in imports) + '\n' + body_opts + '\n'.join(tail))
open(os.path.join(T, 'E8.lean'), 'w').write(main)
print('rows', len(rows), 'orbs', len(orbs), 'tail', len(tail))
