# Independent check of the H4 icosian model and constituent. Imports nothing from the package.
# NOTE: parts of this checker are numerical (matrix_rank, QR, pinv, float characters).
# Treat it as corroboration; the exact companion is explicit_constituents.py h4 (exact Q(sqrt5) arithmetic).
import itertools, sys
from fractions import Fraction as F
import numpy as np
import sympy
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from quadratic_field import Q5, PHI, PHIi

Z, ONE = Q5(0), Q5(1)
half = Q5(F(1, 2))

def qmul(x, y):
    a1, b1, c1, d1 = x; a2, b2, c2, d2 = y
    return (a1*a2 - b1*b2 - c1*c2 - d1*d2,
            a1*b2 + b1*a2 + c1*d2 - d1*c2,
            a1*c2 - b1*d2 + c1*a2 + d1*b2,
            a1*d2 + b1*c2 - c1*b2 + d1*a2)
def qconj(x): return (x[0], -x[1], -x[2], -x[3])
def qneg(x): return tuple(-c for c in x)
def key(x): return tuple(c.key() for c in x)
def ip(x, y): return x[0]*y[0] + x[1]*y[1] + x[2]*y[2] + x[3]*y[3]

EVEN = [p for p in itertools.permutations(range(4))
        if sum(1 for i in range(4) for j in range(i+1, 4) if p[i] > p[j]) % 2 == 0]

def roots_paper():
    R = {}
    for i in range(4):
        for s in (2, -2):
            v = [Z]*4; v[i] = Q5(s); R[key(v)] = tuple(v)
    for sg in itertools.product((1, -1), repeat=4):
        v = tuple(Q5(s) for s in sg); R[key(v)] = v
    base = [PHI, ONE, PHIi, Z]
    for p in EVEN:
        for sg in itertools.product((1, -1), repeat=3):
            vals = [base[0]*sg[0], base[1]*sg[1], base[2]*sg[2], Z]
            v = [None]*4
            for i in range(4): v[p[i]] = vals[i]   # put base entry i at position p[i]
            v = tuple(v); R[key(v)] = v
    return list(R.values())

Rt = roots_paper()
print("number of H4 roots (paper coordinates):", len(Rt))
I = [tuple(c*half for c in r) for r in Rt]
Ikeys = {key(x): x for x in I}
closed = all(key(qmul(x, y)) in Ikeys for x in I for y in I)
print("halved roots closed under quaternion multiplication:", closed)
# norms
print("all unit:", all(ip(x, x) == ONE for x in I))
# the root system is closed under its reflections?
def refl(r, x):  # x - 2(x,r)/(r,r) r
    c = (ip(x, r) * 2) / ip(r, r)
    return tuple(xi - c*ri for xi, ri in zip(x, r))
print("root set closed under its reflections:", all(key(refl(r, x)) in Ikeys for r in I for x in I))
print("reflection formula s_r(x) = -r xbar r:", all(key(refl(r, x)) == key(qneg(qmul(qmul(r, qconj(x)), r))) for r in I for x in I))

# lines / K
def canon(x):
    for c in x:
        if not c.iszero():
            return x if c.ispos() else qneg(x)
Kl = sorted({key(canon(x)) for x in I})
Kidx = {k: i for i, k in enumerate(Kl)}
Kel = [Ikeys[k] for k in Kl]
N = len(Kl)
print("|K| =", N)
def kid(x): return Kidx[key(canon(x))]
mulT = [[kid(qmul(x, y)) for y in Kel] for x in Kel]
invT = [kid(qconj(x)) for x in Kel]
e = kid((ONE, Z, Z, Z))

# rho(W) generated by reflections x -> r x^{-1} r on K
gens = [tuple(mulT[mulT[r][invT[x]]][r] for x in range(N)) for r in range(N)]
# check equals conjugation action of reflections on reflections
def compose(p, q): return tuple(p[q[i]] for i in range(N))   # p after q
idp = tuple(range(N))
G = {idp}; frontier = [idp]
while frontier:
    nf = []
    for g in frontier:
        for s in gens:
            h = compose(s, g)
            if h not in G: G.add(h); nf.append(h)
    frontier = nf
print("|rho(W)| =", len(G), "(expect 7200)")
# the group {x -> a x^{+-1} b}
H = set()
for a in range(N):
    for b in range(N):
        H.add(tuple(mulT[mulT[a][x]][b] for x in range(N)))
        H.add(tuple(mulT[mulT[a][invT[x]]][b] for x in range(N)))
print("rho(W) == {x -> a x^(+-1) b}:", G == H)
Glist = sorted(G)
# centralizer of rho(W) in Sym(K) trivial: stabiliser of e fixes only e
stab = [g for g in Glist if g[e] == e]
fixed = [x for x in range(N) if all(g[x] == x for g in stab)]
print("points fixed by Stab(1):", len(fixed), "=> centraliser trivial:", len(fixed) == 1)

# involutions of K and Klein four subgroups
inv = [x for x in range(N) if x != e and mulT[x][x] == e]
print("involutions in K:", len(inv))
kleins = set()
for x in inv:
    for y in inv:
        if x < y and mulT[x][y] == mulT[y][x]:
            z = mulT[x][y]
            kleins.add(tuple(sorted((x, y, z))))
kleins = sorted(kleins)
print("Klein four-subgroups:", len(kleins))
kl_of = {}
for i, kk in enumerate(kleins):
    for x in kk: kl_of[x] = i
def act5(x):  # conjugation x k x^{-1} on Klein subgroups
    return tuple(kl_of[mulT[mulT[x][kleins[i][0]]][invT[x]]] for i in range(5))
P5 = [act5(x) for x in range(N)]
# matrix coefficient functions delta_{ab}(x) = [x.a = b]
D = np.array([[1 if P5[x][a] == b else 0 for x in range(N)] for a in range(5) for b in range(5)], dtype=float)
print("rank of span of delta_ab:", np.linalg.matrix_rank(D))
Usp = sympy.Matrix([[sympy.Rational(int(D[r, x])) - sympy.Rational(1, 5) for x in range(N)] for r in range(25)])
UB = Usp.T.columnspace()     # basis of U (60 x 16)
B = sympy.Matrix.hstack(*UB)
print("dim U =", B.shape[1])

# orbitals of rho(W) on K x K
parent = list(range(N*N))
def find(a):
    while parent[a] != a:
        parent[a] = parent[parent[a]]; a = parent[a]
    return a
for g in gens:
    for a in range(N):
        for b in range(N):
            x, y = find(a*N+b), find(g[a]*N+g[b])
            if x != y: parent[x] = y
orbs = {}
for p in range(N*N): orbs.setdefault(find(p), []).append(p)
print("number of orbitals of rho(W) on K x K:", len(orbs))
scal = []
for o in orbs.values():
    M = sympy.zeros(N, N)
    for p in o:
        a, b = divmod(p, N); M[a, b] = 1
    MB = M*B
    # MB = c B ?
    # find c from first nonzero entry
    c = None; ok = True
    for i in range(N):
        for j in range(B.shape[1]):
            if B[i, j] != 0:
                c = MB[i, j]/B[i, j]; break
        if c is not None: break
    ok = (MB - c*B) == sympy.zeros(N, B.shape[1])
    scal.append(ok)
print("every orbital matrix acts on U as a scalar (exact):", all(scal))
# commutant eigen-decomposition dims (numerical): random combination of orbital matrices
rng = np.random.default_rng(1)
Mc = np.zeros((N, N))
for o in orbs.values():
    c = rng.normal()
    for p in o:
        a, b = divmod(p, N); Mc[a, b] += c
Mc = (Mc + Mc.T)/2
w = np.linalg.eigvalsh(Mc)
ws = np.sort(w); groups = []
for v in ws:
    if groups and abs(v - groups[-1][-1]) < 1e-6: groups[-1].append(v)
    else: groups.append([v])
print("isotypic dims of C^T (from commutant):", sorted(len(g) for g in groups))

# characters numerically
Bn = np.array(B.tolist(), dtype=float)
Q, _ = np.linalg.qr(Bn)
Pu = Q @ Q.T
def pm(g):
    M = np.zeros((N, N))
    for i in range(N): M[g[i], i] = 1
    return M
chiU = np.array([np.trace(Pu @ pm(g)) for g in Glist])
chiT = np.array([sum(1 for i in range(N) if g[i] == i) for g in Glist])
print("<chi_U,chi_U> =", round(float(chiU @ chiU)/len(Glist), 6), " <chi_U,chi_T> =", round(float(chiU @ chiT)/len(Glist), 6))

# ---- outer automorphism: own construction. sigma = Galois conj on coordinates, followed by a rotation c
# in the 24 signed-permutation rotations of the imaginary part (inner automorphisms of H).
def galois(x): return tuple(c.conj() for c in x)
rots = []
for p in itertools.permutations(range(3)):
    for sg in itertools.product((1, -1), repeat=3):
        M = np.zeros((3, 3), dtype=int)
        for i in range(3): M[p[i], i] = sg[i]
        if round(np.linalg.det(M)) == 1: rots.append(M)
def applyrot(M, x):
    im = [x[1], x[2], x[3]]
    out = [Z, Z, Z]
    for i in range(3):
        for j in range(3):
            if M[i, j]: out[i] = out[i] + im[j]*int(M[i, j])
    return (x[0], out[0], out[1], out[2])
print("sigma alone preserves I:", all(key(galois(x)) in Ikeys for x in I))
good_rots = [M for M in rots if all(key(applyrot(M, galois(x))) in Ikeys for x in I)]
print("number of rotations c (of 24) with c o sigma preserving I:", len(good_rots))
# paper's P: j -> k, k -> -j  (coords (1,i,j,k) -> (1,i,-k?,...)): P(a+bi+cj+dk) = a + bi + c k - d j
def Ppaper(x): return (x[0], x[1], -x[3], x[2])
Psi = lambda x: Ppaper(galois(x))
print("paper's Psi = P o sigma preserves I:", all(key(Psi(x)) in Ikeys for x in I))
print("Psi multiplicative on I:", all(key(Psi(qmul(x, y))) == key(qmul(Psi(x), Psi(y))) for x in I[:40] for y in I))
pi = tuple(kid(Psi(x)) for x in Kel)
Gset = G
def conjg(g): # pi g pi^-1
    pinv = [0]*N
    for i in range(N): pinv[pi[i]] = i
    return tuple(pi[g[pinv[i]]] for i in range(N))
print("pi_Psi normalises rho(W):", all(conjg(s) in Gset for s in gens))
print("pi_Psi in rho(W) (would mean inner, as centraliser trivial):", pi in Gset)
# realness check used in paper
o5 = [x for x in Kel if x[0] == PHI*half or x[0] == -(PHI*half)]
print("elements with real part +-phi/2:", len(o5), " Psi real part of one:", Psi(o5[0])[0])

# witnesses: eigen-dims of h*pi on U for all h
Bpinv = np.linalg.pinv(Bn)
seen = {}
for idx, h in enumerate(Glist):
    hp = compose(h, pi)
    Mh = Bpinv @ pm(hp) @ Bn
    if not np.allclose(Bn @ Mh, pm(hp) @ Bn, atol=1e-8):
        raise SystemExit("U not invariant!")
    dp = 16 - np.linalg.matrix_rank(Mh - np.eye(16), tol=1e-7)
    dm = 16 - np.linalg.matrix_rank(Mh + np.eye(16), tol=1e-7)
    seen.setdefault((dp, dm), idx)
print("(dim +1, dim -1) of h*pi_Psi on U over all h in rho(W):", sorted(seen))
# exact verification of the (10,6) witness
if (10, 6) in seen:
    h = Glist[seen[(10, 6)]]; hp = compose(h, pi)
    Pm = sympy.zeros(N, N)
    for i in range(N): Pm[hp[i], i] = 1
    PB = Pm*B
    # solve B X = PB exactly
    X = (B.T*B).inv()*(B.T*PB)
    assert B*X == PB
    print("exact: order of h*pi on U is 2:", X*X == sympy.eye(16),
          " dims:", 16 - (X - sympy.eye(16)).rank(), 16 - (X + sympy.eye(16)).rank())
    # is hp of order 2 as a permutation, and is it x -> tau x tau^-1 for an outer automorphism of K?
    print("  h*pi fixes identity of K:", hp[e] == e, " is automorphism of K:",
          all(hp[mulT[x][y]] == mulT[hp[x]][hp[y]] for x in range(N) for y in range(N)))
# eps=+1 with h = 1 directly?
print("h = 1 gives dims:", [k for k, v in seen.items() if v == Glist.index(idp)])
